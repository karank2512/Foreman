import type { AgentComponent, BlueprintComponent, DeterministicComponent } from "@/server/domain";
import { parseJsonAnswer, runDeterministic, type ReportMeta } from "@/server/runtime";

/**
 * Did the model do the mechanical steps right? For every converted step of a baseline run, the exact input the
 * model was given is rebuilt (replayed records + the answers of the steps before it), Foreman's deterministic code
 * is run on that input, and the result is compared with what the model answered. Pure.
 *
 * The same walk checks the pairing itself: replaying the AFTER run's collector answer through AFTER's code must
 * reproduce the AFTER run's own records and stats, or the baselines would not be starting from the same input.
 */

export interface StepFidelity {
  componentId: string;
  /** Ids of Foreman's deterministic steps this model call replaced. */
  replaces: string[];
  kind: "records" | "object" | "text";
  exact: boolean;
  /** Records: how many the code kept, how many the model returned, and how they differ. */
  expectedCount?: number;
  actualCount?: number;
  /** Records the code kept that are absent (or altered) in the model's answer. */
  missing?: number;
  /** Records in the model's answer the code would not have produced (altered or invented). */
  unexpected?: number;
  /** Same records, different order. */
  reordered?: boolean;
  /** Text: lines that differ (the date line excluded — the model is not told today's date). */
  differingLines?: number;
}

export interface PairFidelity {
  available: boolean;
  note: string | null;
  steps: StepFidelity[];
  /** For each JSON key a converted step wrote: does the baseline's final value equal AFTER's (code on the same records)? */
  matchesAfter: Record<string, boolean>;
}

export type AgentOutput = { ok: true; value: unknown } | { ok: false; error: string };

/** An agent's final answer as the runtime turns it into its output (agent-loop.ts). */
export function agentOutput(component: Pick<AgentComponent, "outputFormat">, text: string): AgentOutput {
  if (component.outputFormat !== "json") return { ok: true, value: text };
  const parsed = parseJsonAnswer(text);
  return parsed.ok ? { ok: true, value: parsed.value } : { ok: false, error: parsed.error };
}

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value === null || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((k) => [k, sortKeys((value as Record<string, unknown>)[k])]),
  );
}
export const canonical = (value: unknown) => JSON.stringify(sortKeys(value)) ?? "undefined";

function multisetMinus(a: readonly string[], b: readonly string[]): number {
  const counts = new Map<string, number>();
  for (const x of b) counts.set(x, (counts.get(x) ?? 0) + 1);
  let left = 0;
  for (const x of a) {
    const n = counts.get(x) ?? 0;
    if (n > 0) counts.set(x, n - 1);
    else left += 1;
  }
  return left;
}

const DATE_LINE = /^- Generated by .*$/;
function textLines(text: string): string[] {
  const lines = text
    .split(/\r?\n/)
    .map((l) => l.trimEnd())
    .filter((l) => !DATE_LINE.test(l.trim()));
  const collapsed: string[] = [];
  for (const line of lines) if (!(line === "" && collapsed[collapsed.length - 1] === "")) collapsed.push(line);
  while (collapsed[0] === "") collapsed.shift();
  while (collapsed[collapsed.length - 1] === "") collapsed.pop();
  return collapsed;
}

export function compareOutputs(expected: unknown, actual: unknown): Omit<StepFidelity, "componentId" | "replaces"> {
  if (typeof expected === "string") {
    const want = textLines(expected);
    const got = typeof actual === "string" ? textLines(actual) : [];
    const exact = want.length === got.length && want.every((l, i) => l === got[i]);
    return { kind: "text", exact, differingLines: exact ? 0 : Math.max(multisetMinus(want, got), multisetMinus(got, want), 1) };
  }
  if (Array.isArray(expected)) {
    const want = expected.map(canonical);
    const got = Array.isArray(actual) ? actual.map(canonical) : [];
    const missing = multisetMinus(want, got);
    const unexpected = multisetMinus(got, want);
    const exact = want.length === got.length && want.every((r, i) => r === got[i]);
    return { kind: "records", exact, expectedCount: want.length, actualCount: got.length, missing, unexpected, reordered: !exact && missing === 0 && unexpected === 0 };
  }
  return { kind: "object", exact: canonical(expected) === canonical(actual) };
}

/** Run `steps` in order, the way the runtime runs deterministic components, on a copy of `context`. */
export function runChain(steps: readonly DeterministicComponent[], context: Record<string, unknown>, meta: ReportMeta): unknown {
  const ctx = { ...context };
  let value: unknown;
  for (const step of steps) {
    value = runDeterministic(step, ctx, meta).value;
    ctx[step.outputKey] = value;
  }
  return value;
}

const pick = (context: Record<string, unknown>, keys: readonly string[]) => Object.fromEntries(keys.map((k) => [k, context[k]]));

interface WalkArgs {
  components: readonly BlueprintComponent[];
  startIndex: number;
  startContext: Record<string, unknown>;
  /** Final answer text per agent component of the run being walked. */
  answers: ReadonlyMap<string, string>;
  /** Converted agents of a baseline → the deterministic steps they replace (empty for AFTER). */
  converted: ReadonlyMap<string, readonly DeterministicComponent[]>;
  meta: ReportMeta;
  /** The run's own final context: deterministic reports (whose footer needs run facts) are taken from it, not rebuilt. */
  runFinal: Record<string, unknown>;
}

interface WalkResult {
  context: Record<string, unknown>;
  steps: StepFidelity[];
  /** Keys taken from the run rather than rebuilt; excluded when the walk is checked against the run. */
  taken: Set<string>;
  error: string | null;
}

/** Re-traces a run from `startIndex`: agents from their answers, code by running it, converted steps compared with code. */
export function walkRun(args: WalkArgs): WalkResult {
  const context: Record<string, unknown> = { ...args.startContext };
  const steps: StepFidelity[] = [];
  const taken = new Set<string>();
  for (const component of args.components.slice(args.startIndex)) {
    if (component.type === "deterministic") {
      if (component.operation === "compile_report") {
        context[component.outputKey] = args.runFinal[component.outputKey];
        taken.add(component.outputKey);
      } else {
        context[component.outputKey] = runDeterministic(component, context, args.meta).value;
      }
      continue;
    }
    const text = args.answers.get(component.id);
    if (text === undefined) return { context, steps, taken, error: `no captured answer for ${component.id}` };
    const output = agentOutput(component, text);
    if (!output.ok) return { context, steps, taken, error: `${component.id}'s answer could not be parsed: ${output.error}` };
    const replaces = args.converted.get(component.id);
    if (replaces) {
      // The model saw only its input keys; the code is given exactly those.
      const expected = runChain(replaces, pick(context, component.inputKeys), args.meta);
      steps.push({ componentId: component.id, replaces: replaces.map((s) => s.id), ...compareOutputs(expected, output.value) });
    }
    context[component.outputKey] = output.value;
  }
  return { context, steps, taken, error: null };
}

/** Keys whose rebuilt value differs from the run's own final value. */
export function mismatchedKeys(walk: WalkResult, runFinal: Record<string, unknown>, keys: readonly string[]): string[] {
  return keys.filter((k) => !walk.taken.has(k) && canonical(walk.context[k]) !== canonical(runFinal[k]));
}
